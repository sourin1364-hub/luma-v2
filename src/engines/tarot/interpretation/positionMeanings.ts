/**
 * دریافت معنی موقعیت‌محور برای یک کارت.
 * اگر معنی اختصاصی وجود نداشت، null برمی‌گرداند.
 */
export function getPositionSpecificMeaning(
  spreadId: string,
  positionIndex: number,
  cardId: string
): string | null {
  const spreadMeanings = POSITION_MEANINGS[spreadId];
  if (!spreadMeanings) return null;
  const positionMeanings = spreadMeanings[positionIndex];
  if (!positionMeanings) return null;
  return positionMeanings[cardId] || null;
}